function renderLibraryCards() {
    const grid = document.getElementById("catalog-grid");
    if (!grid) return;

    grid.innerHTML = libraryItems.map(function (item) {
        const featuredClass = item.featured ? " featured" : "";
        const placeholderClass = item.featured ? " large" : "";
        const mediaInner = item.image
            ? `<div class="threedimg" style="background-image: url('${item.image}');"></div>`
            : "";

        return `
            <div class="info-card${featuredClass}">
                <div class="info-img-placeholder${placeholderClass}" data-caption="${item.caption || ""}">
                    ${mediaInner}
                </div>
                <h3 id="${item.id}-title" class="khmer-title">${item.khmerTitle}</h3>
                <p id="${item.id}-text" class="khmer-text">${item.khmer}</p>
            </div>
        `;
    }).join("");
}

